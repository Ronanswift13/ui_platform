def _script_line(script_name: str, base: Path, module_placeholder: str = "<module>") -> str:
    """生成脚本调用行，标注是否真实存在。"""
    exists = (base / "scripts" / script_name).is_file()
    cmd = f"./scripts/{script_name}"
    if "targeted" in script_name:
        cmd += f" {module_placeholder}"
    if exists:
        return f"   - `{cmd}` — 等待实际输出"
    return f"   - ~~`{cmd}`~~ — 脚本不存在，跳过"


