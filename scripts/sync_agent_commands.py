@dataclass
class CommandStatus:
    """单个 command 文件的状态。"""
    cmd_type: str
    path: Path
    exists: bool = False
    has_routing_ref: bool = False
    is_auto_generated: bool = False
    action: str = "create"  # create / update / skip
    reason: str = ""


def evaluate_existing_command(base: Path, cmd_type: str) -> CommandStatus:
    """评估一个已有的 command 文件。"""
    cmd_path = base / ".claude" / "commands" / f"{cmd_type}.md"
    status = CommandStatus(cmd_type=cmd_type, path=cmd_path)

    if not cmd_path.is_file():
        status.action = "create"
        status.reason = "文件不存在"
        return status

    status.exists = True
    content = cmd_path.read_text(encoding="utf-8")
    status.has_routing_ref = ROUTING_ANCHOR in content
    status.is_auto_generated = SYNC_MARKER in content

    if status.has_routing_ref and not status.is_auto_generated:
        # 人工编写且已接入路由 — 保留
        status.action = "skip"
        status.reason = "已有合格内容 (人工编写，已接入路由)"
    elif status.is_auto_generated:
        # 自动生成的，可安全更新
        status.action = "update"
        status.reason = "自动生成文件，可安全更新"
    elif not status.has_routing_ref:
        # 存在但未接入路由
        status.action = "update"
        status.reason = "未接入 08_task_routing.md，需更新"
    else:
        status.action = "skip"
        status.reason = "已有合格内容"

    return status


