def format_check_output(actions: list[SyncAction], ineligible: list[dict]) -> str:
    lines = []
    sep = "=" * 78

    # 不符合条件的对象
    lines.append(sep)
    lines.append("[不符合生成条件的对象]")
    lines.append(sep)
    if ineligible:
        for item in ineligible:
            lines.append(f"  ✗ {item['name']:<28} — {item['reason']}")
    else:
        lines.append("  (无)")
    lines.append("")

    # 按 action 分组
    creates = [a for a in actions if a.action == "create"]
    updates = [a for a in actions if a.action == "update"]
    skips = [a for a in actions if a.action == "skip"]

    lines.append(sep)
    lines.append(f"[同步计划] 新建: {len(creates)} / 更新: {len(updates)} / 跳过: {len(skips)}")
    lines.append(sep)

    # 按目标分组展示
    targets = {}
    for a in actions:
        targets.setdefault(a.target_name, []).append(a)

    for name, acts in sorted(targets.items()):
        level = acts[0].governance_level
        obj_type = acts[0].target_type
        lines.append(f"\n  {name} ({obj_type}, {level}):")
        for a in acts:
            icon = {"create": "+", "update": "~", "skip": "="}[a.action]
            lines.append(f"    [{icon}] {a.cmd_type:12} — {a.action:6} | {a.reason}")

    lines.append("")
    return "\n".join(lines)


def format_apply_output(results_log: list[dict]) -> str:
    lines = ["", "=" * 78, "[同步结果]", "=" * 78]
    created = sum(1 for r in results_log if r["action"] == "create")
    updated = sum(1 for r in results_log if r["action"] == "update")
    skipped = sum(1 for r in results_log if r["action"] == "skip")

    for r in results_log:
        icon = {"create": "✓ 新建", "update": "✓ 更新", "skip": "— 跳过"}[r["action"]]
        path_str = f"  → {r.get('path', '')}" if r.get("path") else ""
        lines.append(f"  {icon} {r['target']}/{r['cmd']}.md{path_str}")

    lines.append(f"\n  汇总: {created} 新建 / {updated} 更新 / {skipped} 跳过")
    return "\n".join(lines)


