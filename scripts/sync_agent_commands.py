@dataclass
class SyncAction:
    target_name: str
    target_type: str
    governance_level: str
    cmd_type: str
    path: str
    action: str  # create / update / skip
    reason: str


def build_sync_plan(repo_root: Path) -> tuple[list[SyncAction], list[dict]]:
    """构建同步计划，返回 (actions, ineligible_list)。"""
    results = scan_all(repo_root)
    actions = []
    ineligible = []

    for gov in results:
        # 缓存 base path
        if gov.scope == "root":
            base = repo_root
        elif gov.scope == "ui":
            base = repo_root / "ui"
        else:
            base = repo_root / "plugins" / gov.name
        _BASE_CACHE[gov.name] = base

        # root 不生成 commands (总路由角色)
        if gov.scope == "root":
            ineligible.append({
                "name": gov.name, "reason": "root 是总路由角色，不生成插件级 commands",
            })
            continue

        eligible, reason = is_eligible(gov)
        if not eligible:
            ineligible.append({"name": gov.name, "reason": reason})
            continue

        for cmd_type in COMMAND_TYPES:
            status = evaluate_existing_command(base, cmd_type)
            actions.append(SyncAction(
                target_name=gov.name,
                target_type=gov.object_type,
                governance_level=gov.governance_level,
                cmd_type=cmd_type,
                path=str(status.path),
                action=status.action,
                reason=status.reason,
            ))

    return actions, ineligible


# ---------------------------------------------------------------------------
# 执行写入
# ---------------------------------------------------------------------------

def apply_sync(repo_root: Path, actions: list[SyncAction]) -> list[dict]:
    """执行同步写入，返回结果列表。"""
    results_log = []

    for act in actions:
        if act.action == "skip":
            results_log.append({
                "target": act.target_name,
                "cmd": act.cmd_type,
                "action": "skip",
                "reason": act.reason,
            })
            continue

        # 解析 base
        base = _BASE_CACHE.get(act.target_name)
        if not base:
            continue

        # 获取治理信息
        scope = "ui" if act.target_name == "ui" else "plugin"
        gov = scan_target(act.target_name, base, scope)
        _BASE_CACHE[gov.name] = base

        # 生成内容
        generator = GENERATORS.get(act.cmd_type)
        if not generator:
            continue

        content = generator(gov, base)

        # 写入
        cmd_path = Path(act.path)
        cmd_path.parent.mkdir(parents=True, exist_ok=True)
        cmd_path.write_text(content, encoding="utf-8")

        results_log.append({
            "target": act.target_name,
            "cmd": act.cmd_type,
            "action": act.action,
            "path": str(cmd_path),
            "reason": act.reason,
        })

    return results_log


