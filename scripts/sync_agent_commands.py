def is_eligible(gov: GovernanceResult) -> tuple[bool, str]:
    """判断一个对象是否符合生成 commands 的条件。"""
    if gov.governance_level == "L0":
        return False, "L0 占位态，无治理基础"

    if not gov.has_agent_skills:
        return False, "缺少 .agent_skills/ 目录"

    # 必须有 08_task_routing.md
    base = _resolve_base(gov)
    if base and not (base / ".agent_skills" / "08_task_routing.md").is_file():
        return False, "缺少 .agent_skills/08_task_routing.md"

    # 至少有一个可执行脚本
    if not gov.scripts_present:
        # 允许有 tests/ 目录的也算 (可用 pytest 直接跑)
        if "tests" not in gov.dirs_present:
            return False, "无可用脚本且无 tests/ 目录"

    return True, "符合条件"


# 缓存: name -> base path
_BASE_CACHE: dict[str, Path] = {}


def _resolve_base(gov: GovernanceResult) -> Optional[Path]:
    return _BASE_CACHE.get(gov.name)


